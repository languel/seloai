/** `level` is an older name for the World editor and `tapestry` for the Pattern Studio, still accepted. */
export type WorkspaceTabId = 'village' | 'observatory' | 'world' | 'patterns' | 'level' | 'tapestry' | 'characters' | 'monitor' | 'guides';

export interface SeloHostHooks {
  getSimulation: () => VillageSimulation;
  getMap: () => VillageMap;
  getVillagers: () => VillagerConfig[];
  getSettings: () => ModelSettings;
  getTab?: () => WorkspaceTabId;
  setTab?: (tab: WorkspaceTabId) => void;
  applyMap: (nextMap: VillageMap) => void;
  applyVillagers: (nextVillagers: VillagerConfig[]) => void;
  updateSettings: (patch: Partial<ModelSettings>) => void;
  persistAll?: () => void;
  /** The world store, when the host routes edits through commands (enables undo). */
  getStore?: () => WorldStore;
  /** A PNG data URL of the current view, where the host has one. */
  captureView?: () => Promise<string | null>;
}

export interface SeloToolDefinition {
  name: string;
  description: string;
  inputSchema: Record<string, any>;
}

function redactSettings(s: ModelSettings): Record<string, any> {
  return {
    ...s,
    localApiKey: s.localApiKey ? '***' : '',
    voiceApiKey: s.voiceApiKey ? '***' : '',
    imageGenApiKey: s.imageGenApiKey ? '***' : '',
  };
}

function findVillagerMatch(villagers: VillagerConfig[], query?: string): VillagerConfig | undefined {
  if (!query) return undefined;
  const q = query.trim().replace(/^@/, '').toLowerCase();
  return (
    villagers.find((v) => v.id.toLowerCase() === q) ??
    villagers.find((v) => v.name.toLowerCase() === q) ??
    villagers.find((v) => v.name.toLowerCase().startsWith(q))
  );
}

/** The authoring tools first: they are the plain way in for an agent making a world. */
export const SELO_TOOL_DEFINITIONS: SeloToolDefinition[] = [...AUTHORING_TOOL_DEFINITIONS, ...(toolSchemas as SeloToolDefinition[])];

export class SeloToolHost {
  constructor(private hooks: SeloHostHooks) {}

  setHooks(hooks: SeloHostHooks) {
    this.hooks = hooks;
  }

  listTools(): SeloToolDefinition[] {
    return SELO_TOOL_DEFINITIONS;
  }

  private requireStore(): WorldStore {
    const store = this.hooks.getStore?.();
    if (!store) throw new Error('World commands are not available in this host.');
    return store;
  }

  async callTool(name: string, args: Record<string, any> = {}): Promise<any> {
    const sim = this.hooks.getSimulation();
    const map = this.hooks.getMap();
    const villagers = this.hooks.getVillagers();
    const settings = this.hooks.getSettings();

    brainRouter.log({
      channel: 'mcp',
      level: 'info',
      title: `Tool: ${name}`,
      detail: JSON.stringify(args).slice(0, 140),
    });

    if (isAuthoringTool(name)) {
      return runAuthoringTool(name, args, {
        store: this.requireStore(),
        sim,
        captureView: this.hooks.captureView,
        persist: this.hooks.persistAll,
      });
    }

    switch (name) {
      case 'get_world_state': {
        const includeMessages = args.includeMessages !== false;
        return {
          tab: this.hooks.getTab?.() ?? 'village',
          simulation: {
            paused: sim.paused,
            speedMultiplier: sim.speedMultiplier,
            fps: sim.fps,
            focalWorldlineId: sim.focalWorldlineId,
            listener: sim.getListenerPosition(),
            player: { x: sim.player.x, y: sim.player.y, facing: sim.player.facing },
          },
          map: {
            name: map.name,
            width: map.width,
            height: map.height,
            tileDim: map.tileDim,
            tileSetUrl: map.tileSetUrl,
            pointsOfInterest: map.pointsOfInterest ?? [],
            spawnPoints: map.spawnPoints,
            stampsCount: map.stamps?.length ?? 0,
            animatedSpritesCount: map.animatedSprites.length,
          },
          villagers: villagers.map((v) => {
            const rt = sim.runtimes.get(v.id);
            return {
              id: v.id,
              name: v.name,
              role: v.role,
              plan: v.plan,
              x: rt?.x ?? v.homeTile.x,
              y: rt?.y ?? v.homeTile.y,
              state: rt?.state ?? 'idle',
              currentIntention: rt?.currentIntention ?? v.plan,
              memoryCount: rt?.memories.length ?? 0,
            };
          }),
          conversations: includeMessages
            ? sim.conversations.slice(0, 10)
            : sim.conversations.map((c) => ({ id: c.id, count: c.messages.length, updatedAt: c.updatedAt })),
          settings: redactSettings(settings),
        };
      }

      case 'control_simulation': {
        if (typeof args.paused === 'boolean') sim.paused = args.paused;
        if (typeof args.speedMultiplier === 'number' && Number.isFinite(args.speedMultiplier)) {
          sim.speedMultiplier = Math.max(-MAX_SPEED, Math.min(MAX_SPEED, args.speedMultiplier));
        }
        if (args.scatter) sim.scatterVillagers();
        if (args.tab && this.hooks.setTab) this.hooks.setTab(args.tab);
        let conversation: any;
        if (Array.isArray(args.startEncounterBetween) && args.startEncounterBetween.length === 2) {
          const a = findVillagerMatch(villagers, args.startEncounterBetween[0]);
          const b = findVillagerMatch(villagers, args.startEncounterBetween[1]);
          if (!a || !b) throw new Error('Could not find both villagers for encounter.');
          conversation = await sim.runConversationBetween(a.id, b.id);
          this.hooks.persistAll?.();
        }
        return {
          ok: true,
          paused: sim.paused,
          speedMultiplier: sim.speedMultiplier,
          conversationId: conversation?.id,
          tab: this.hooks.getTab?.(),
        };
      }

      case 'set_worldline_pov': {
        const target = String(args.target || '').trim();
        if (!target || target.toLowerCase() === 'scribe' || target.toLowerCase() === 'narrator') {
          sim.setFocalWorldline('scribe');
        } else {
          const match = findVillagerMatch(villagers, target);
          if (!match) throw new Error(`Villager "${target}" not found.`);
          sim.setFocalWorldline(match.id);
        }
        this.hooks.persistAll?.();
        return {
          ok: true,
          focalWorldlineId: sim.focalWorldlineId,
          listener: sim.getListenerPosition(),
        };
      }

      case 'create_world': {
        const presetStr = String(args.preset || '').toLowerCase();
        const nameStr = String(args.name || '').toLowerCase();
        const isBalkanMyth =
          presetStr === 'balkan-myth' ||
          presetStr === 'zmeyovo' ||
          presetStr === 'lamia' ||
          nameStr.includes('zmeyovo') ||
          nameStr.includes('lamia');
        const isShevitsa =
          !isBalkanMyth &&
          (presetStr === 'shevitsa' ||
            presetStr === 'bulgaria' ||
            nameStr.includes('shevitsa') ||
            nameStr.includes('bulgaria'));
        const width = isBalkanMyth
          ? Math.max(48, Math.min(80, Number(args.width ?? 48)))
          : Math.max(isShevitsa ? 64 : 12, Math.min(80, Number(args.width ?? (isShevitsa ? 64 : 36))));
        const height = isBalkanMyth
          ? Math.max(36, Math.min(64, Number(args.height ?? 36)))
          : Math.max(isShevitsa ? 48 : 12, Math.min(64, Number(args.height ?? (isShevitsa ? 48 : 28))));
        const balkanBundle = isBalkanMyth ? createBalkanMythWorld(width, height) : null;
        const nextMap = balkanBundle
          ? balkanBundle.map
          : isShevitsa
            ? createBulgarianShevitsaMap(width, height)
            : createBlankWorldMap(args.name || 'Agent World', width, height);
        if (args.name) nextMap.name = String(args.name);
        if (typeof args.tileDim === 'number' && args.tileDim >= 8) nextMap.tileDim = args.tileDim;
        if (typeof args.tileSetUrl === 'string' && args.tileSetUrl.trim()) {
          nextMap.tileSetUrl = args.tileSetUrl.trim();
        }
        if (Array.isArray(args.pois) && args.pois.length > 0) {
          nextMap.pointsOfInterest = args.pois.map((p: any, idx: number) => ({
            id: p.id || `poi-${idx}-${Date.now().toString(36)}`,
            tag: (p.tag || p.label || `POI${idx}`).replace(/[^a-zA-Z0-9_-]/g, ''),
            label: String(p.label || p.tag || `Point ${idx + 1}`),
            x: Math.max(0, Math.min(width - 1, Math.round(Number(p.x)))),
            y: Math.max(0, Math.min(height - 1, Math.round(Number(p.y)))),
            description: p.description ? String(p.description) : undefined,
          }));
        }
        if (args.clearDatabase) {
          sim.clearDatabase();
        }
        const nextContext = worldContextForPack(
          isBalkanMyth ? 'balkan-myth' : isShevitsa ? 'shevitsa' : 'blank',
        );
        const store = this.hooks.getStore?.();
        if (store) {
          const commands: WorldCommand[] = [
            { type: 'context.update', patch: nextContext },
            { type: 'map.replace', map: nextMap },
          ];
          if (balkanBundle && args.includeCast !== false) {
            commands.push({ type: 'cast.replace', cast: balkanBundle.villagers });
          }
          store.dispatchAll(commands, `Create world "${nextMap.name}"`);
        } else {
          sim.setWorld(nextContext);
          this.hooks.applyMap(nextMap);
          if (balkanBundle && args.includeCast !== false) {
            this.hooks.applyVillagers(balkanBundle.villagers);
          }
        }
        return {
          ok: true,
          preset: isBalkanMyth ? 'balkan-myth' : isShevitsa ? 'shevitsa' : 'blank',
          map: {
            name: nextMap.name,
            width: nextMap.width,
            height: nextMap.height,
            pointsOfInterest: nextMap.pointsOfInterest,
          },
          villagersApplied: balkanBundle && args.includeCast !== false ? balkanBundle.villagers.length : 0,
        };
      }

      case 'edit_world_map': {
        let nextMap: VillageMap = structuredClone(map);
        if (typeof args.name === 'string' && args.name.trim()) nextMap.name = args.name.trim();
        if (typeof args.tileSetUrl === 'string' && args.tileSetUrl.trim()) {
          nextMap.tileSetUrl = args.tileSetUrl.trim();
        }
        if (typeof args.tileSetDimX === 'number' && args.tileSetDimX >= 16) {
          nextMap.tileSetDimX = Math.round(args.tileSetDimX);
        }
        if (typeof args.tileSetDimY === 'number' && args.tileSetDimY >= 16) {
          nextMap.tileSetDimY = Math.round(args.tileSetDimY);
        }
        if (typeof args.tileDim === 'number' && args.tileDim >= 8) {
          nextMap.tileDim = args.tileDim;
        }
        if (Array.isArray(args.tileOps)) {
          for (const op of args.tileOps) {
            const x = Math.round(Number(op.x));
            const y = Math.round(Number(op.y));
            if (x < 0 || y < 0 || x >= nextMap.width || y >= nextMap.height) continue;
            if (op.layer === 'collision') {
              if (!nextMap.collisionGrid[x]) nextMap.collisionGrid[x] = Array(nextMap.height).fill(false);
              nextMap.collisionGrid[x][y] = Boolean(op.blocked ?? true);
            } else {
              const grid =
                op.layer === 'bg0'
                  ? nextMap.bgTiles[0]
                  : op.layer === 'bg1'
                    ? (nextMap.bgTiles[1] ??= Array.from({ length: nextMap.width }, () =>
                        Array(nextMap.height).fill(-1),
                      ))
                    : op.layer === 'obj0'
                      ? nextMap.objectTiles[0]
                      : (nextMap.objectTiles[1] ??= Array.from({ length: nextMap.width }, () =>
                          Array(nextMap.height).fill(-1),
                        ));
              if (grid?.[x]) {
                grid[x][y] = typeof op.tileIndex === 'number' ? op.tileIndex : -1;
              }
            }
          }
        }
        if (Array.isArray(args.addStamps) && args.addStamps.length > 0) {
          const existing = [...(nextMap.stamps ?? [])];
          for (const raw of args.addStamps) {
            const st: TileMacroStamp = {
              id: raw.id || `stamp-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`,
              name: String(raw.name || 'Stamp'),
              width: Math.max(1, Math.round(Number(raw.width ?? 1))),
              height: Math.max(1, Math.round(Number(raw.height ?? 1))),
              tiles: Array.isArray(raw.tiles) ? raw.tiles.map(Number) : [0],
              layer: raw.layer ?? 'bg1',
              blocksMovement: Boolean(raw.blocksMovement),
            };
            const idx = existing.findIndex((s) => s.id === st.id);
            if (idx >= 0) existing[idx] = st;
            else existing.push(st);
          }
          nextMap.stamps = existing;
        }
        if (Array.isArray(args.placeStamps) && args.placeStamps.length > 0) {
          const stampsList = nextMap.stamps ?? [];
          for (const req of args.placeStamps) {
            const stampMatch =
              (req.stampId ? stampsList.find((s) => s.id === req.stampId) : undefined) ??
              (req.stampName
                ? stampsList.find((s) => s.name.toLowerCase() === String(req.stampName).toLowerCase())
                : undefined);
            if (stampMatch) {
              nextMap = applyMacroStampToMap(
                nextMap,
                stampMatch,
                Number(req.x ?? 0),
                Number(req.y ?? 0),
                req.layer,
                req.blocksMovement,
              );
            }
          }
        }
        if (Array.isArray(args.removePoiIds) && nextMap.pointsOfInterest) {
          const rm = new Set(args.removePoiIds.map(String));
          nextMap.pointsOfInterest = nextMap.pointsOfInterest.filter((p) => !rm.has(p.id));
        }
        if (Array.isArray(args.addPois)) {
          const pois = [...(nextMap.pointsOfInterest ?? [])];
          for (const p of args.addPois) {
            const poi: PointOfInterest = {
              id: p.id || `poi-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 5)}`,
              tag: String(p.tag || p.label || 'POI').replace(/[^a-zA-Z0-9_-]/g, ''),
              label: String(p.label || p.tag || 'POI'),
              x: Math.max(0, Math.min(nextMap.width - 1, Math.round(Number(p.x)))),
              y: Math.max(0, Math.min(nextMap.height - 1, Math.round(Number(p.y)))),
              description: p.description ? String(p.description) : undefined,
            };
            pois.push(poi);
          }
          nextMap.pointsOfInterest = pois;
        }
        if (Array.isArray(args.addSpawnPoints)) {
          const spawns = [...nextMap.spawnPoints];
          for (const sp of args.addSpawnPoints) {
            spawns.push({
              id: sp.id || `sp-${Date.now().toString(36)}`,
              label: String(sp.label || 'Spawn'),
              x: Math.max(0, Math.min(nextMap.width - 1, Math.round(Number(sp.x)))),
              y: Math.max(0, Math.min(nextMap.height - 1, Math.round(Number(sp.y)))),
            });
          }
          nextMap.spawnPoints = spawns;
        }
        this.hooks.applyMap(nextMap);
        return {
          ok: true,
          name: nextMap.name,
          stampsCount: nextMap.stamps?.length ?? 0,
          pointsOfInterest: nextMap.pointsOfInterest,
        };
      }

      case 'create_character': {
        const seed = createSeededRng(Date.now());
        const baseAuto = createAutoGeneratedVillager({ map, existingVillagers: villagers, rng: seed });
        const nameStr = String(args.name || '').trim() || baseAuto.name;
        const id =
          String(args.id || '').trim() ||
          `v-${nameStr.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${Date.now().toString(36)}`;
        const homeRaw = {
          x: typeof args.x === 'number' ? args.x : baseAuto.homeTile.x,
          y: typeof args.y === 'number' ? args.y : baseAuto.homeTile.y,
        };
        const safe = findNearestWalkableTile(map, homeRaw.x, homeRaw.y);
        const appearance: CharacterAppearance | undefined = args.customSpriteDataUrl
          ? undefined
          : {
              ...DEFAULT_APPEARANCE,
              ...(baseAuto.appearance ?? {}),
              ...(args.appearance ?? {}),
            };
        const cfg: VillagerConfig = ensureVillagerSprite({
          id,
          name: nameStr,
          role: String(args.role || baseAuto.role),
          spritesheetId: args.customSpriteDataUrl ? 'custom' : 'modular',
          appearance,
          customSprite: args.customSpriteDataUrl
            ? {
                textureUrl: String(args.customSpriteDataUrl),
                frameWidth: 32,
                frameHeight: 32,
                cols: 3,
                rows: 4,
                framesPerDirection: 3,
                rowMap: { down: 0, left: 1, right: 2, up: 3 },
              }
            : undefined,
          accentColor: String(args.accentColor || '#6c93bf'),
          identity: String(args.identity || `${nameStr} recently arrived with quiet resolve.`),
          plan: String(args.plan || 'Explore the settlement and learn local rumors.'),
          voiceStyle: String(args.voiceStyle || 'Clear, observant cadence.'),
          voice: {
            gender: args.gender ?? 'female',
            language: args.language ?? 'American English',
            pitchSemitones: 0,
            speakingRate: 1,
            warmthDb: 0,
          },
          homeTile: safe,
          speed: 0.72,
        });
        const existingIdx = villagers.findIndex((v) => v.id === cfg.id || v.name.toLowerCase() === cfg.name.toLowerCase());
        const nextList =
          existingIdx >= 0
            ? villagers.map((v, i) => (i === existingIdx ? cfg : v))
            : [...villagers, cfg];
        this.hooks.applyVillagers(nextList);
        return { ok: true, villager: { id: cfg.id, name: cfg.name, role: cfg.role, homeTile: cfg.homeTile }, totalVillagers: nextList.length };
      }

      case 'batch_create_characters': {
        const count = Math.max(1, Math.min(24, Number(args.count ?? 4)));
        const existing = args.replaceExisting ? [] : villagers;
        const rng = typeof args.seed === 'number' ? createSeededRng(args.seed) : Math.random;
        const generated = createAutomatedVillagerBatch(count, {
          map,
          existingVillagers: existing,
          rng,
        });
        const nextList = args.replaceExisting ? generated : [...existing, ...generated];
        this.hooks.applyVillagers(nextList);
        return {
          ok: true,
          created: generated.map((v) => ({ id: v.id, name: v.name, role: v.role, homeTile: v.homeTile })),
          totalVillagers: nextList.length,
        };
      }

      case 'remove_character': {
        const match = findVillagerMatch(villagers, String(args.target || ''));
        if (!match) throw new Error(`Villager "${args.target}" not found.`);
        const nextList = villagers.filter((v) => v.id !== match.id);
        this.hooks.applyVillagers(nextList);
        return { ok: true, removedId: match.id, remainingCount: nextList.length };
      }

      case 'run_scenario': {
        if (args.clearDatabase) {
          sim.clearDatabase();
        }
        if (args.worldName || args.worldPreset || args.preset || args.width || args.height || Array.isArray(args.pois)) {
          const explicitPreset = args.worldPreset ?? args.preset;
          await this.callTool('create_world', {
            preset: explicitPreset,
            name: args.worldName ?? (explicitPreset ? undefined : map.name),
            width: args.width ?? (explicitPreset ? undefined : map.width),
            height: args.height ?? (explicitPreset ? undefined : map.height),
            pois: args.pois,
            clearDatabase: false,
          });
        }
        if (Array.isArray(args.villagers) && args.villagers.length > 0) {
          const built: VillagerConfig[] = [];
          for (const item of args.villagers) {
            const res = await this.callTool('create_character', item);
            built.push(res.villager);
          }
        }
        if (typeof args.autoVillagerCount === 'number' && args.autoVillagerCount > 0) {
          await this.callTool('batch_create_characters', {
            count: args.autoVillagerCount,
            replaceExisting: Array.isArray(args.villagers) && args.villagers.length === 0,
          });
        }
        if (args.focalWorldlineId) {
          await this.callTool('set_worldline_pov', { target: args.focalWorldlineId });
        }
        let directiveResult: any;
        if (args.openingDirective) {
          directiveResult = await this.callTool('instruct_world', { text: String(args.openingDirective) });
        }
        let encounterResult: any;
        if (Array.isArray(args.startEncounterBetween) && args.startEncounterBetween.length === 2) {
          encounterResult = await this.callTool('control_simulation', {
            startEncounterBetween: args.startEncounterBetween,
          });
        }
        return {
          ok: true,
          world: await this.callTool('get_world_state', { includeMessages: false }),
          directiveResult,
          encounterResult,
        };
      }

      case 'instruct_world': {
        const text = String(args.text || '').trim();
        if (!text) throw new Error('text is required.');
        const targetId = args.recipientId
          ? args.recipientId === 'narrator' || String(args.recipientId).toLowerCase() === 'scribe'
            ? 'narrator'
            : (findVillagerMatch(villagers, args.recipientId)?.id ?? String(args.recipientId))
          : villagers[0]?.id ?? 'narrator';
        const res = await sim.sendUserAddressedMessage(targetId, text, false);
        const latestConv = sim.conversations[0];
        this.hooks.persistAll?.();
        return {
          ok: true,
          focusedTargetId: res.focusedTargetId,
          conversationId: latestConv?.id,
          messages: latestConv?.messages.slice(-8) ?? [],
        };
      }

      case 'move_actor': {
        const actorKey = String(args.actor || 'player').trim().toLowerCase();
        let goal = { x: Number(args.x ?? map.width / 2), y: Number(args.y ?? map.height / 2) };
        if (args.poi) {
          const norm = String(args.poi).replace(/^#/, '').toLowerCase();
          const poi = (map.pointsOfInterest ?? []).find(
            (p) =>
              p.tag.toLowerCase() === norm ||
              p.label.toLowerCase() === norm ||
              p.label.toLowerCase().includes(norm),
          );
          if (!poi) throw new Error(`POI "${args.poi}" not found.`);
          goal = { x: poi.x, y: poi.y };
        }
        const safe = findNearestWalkableTile(map, goal.x, goal.y);
        if (actorKey === 'player') {
          sim.movePlayerTo(safe.x, safe.y);
          return { ok: true, actor: 'player', target: safe };
        }
        const v = findVillagerMatch(villagers, actorKey);
        if (!v) throw new Error(`Actor "${args.actor}" not found.`);
        const rt = sim.runtimes.get(v.id);
        if (!rt) throw new Error(`Runtime for "${v.name}" not found.`);
        rt.path = findPath(map, { x: rt.x, y: rt.y }, safe);
        rt.state = rt.path.length > 0 ? 'walking' : rt.state;
        rt.currentIntention = args.poi ? `Heading to #${String(args.poi).replace(/^#/, '')}` : `Walking to (${safe.x}, ${safe.y})`;
        rt.activityLabel = rt.currentIntention;
        sim.notify(true);
        return { ok: true, actor: v.name, target: safe, pathSteps: rt.path.length };
      }

      case 'query_world_db': {
        const limit = Math.max(1, Math.min(200, Number(args.limit ?? 50)));
        const nl = args.query ? queryWorldDatabase(sim, String(args.query)) : undefined;
        let records = buildWorldDatabase(sim);
        if (args.actorId) {
          const aId = String(args.actorId).toLowerCase();
          records = records.filter(
            (r) => r.actorId.toLowerCase() === aId || r.actorName.toLowerCase() === aId,
          );
        }
        if (args.kind) {
          records = records.filter((r) => r.kind === args.kind);
        }
        return {
          totalRecords: records.length,
          records: records.slice(0, limit),
          queryResult: nl,
          graph: args.includeGraph ? buildPsychophysicalGraph(sim) : undefined,
        };
      }

      case 'configure_backends': {
        const patch: Partial<ModelSettings> = {};
        const keys: Array<keyof ModelSettings> = [
          'inferenceMode',
          'localApiEnabled',
          'localApiProvider',
          'localApiUrl',
          'localApiKey',
          'localApiModel',
          'voiceApiEnabled',
          'voiceProvider',
          'voiceApiUrl',
          'voiceApiKey',
          'voiceApiModel',
          'imageGenEnabled',
          'imageGenProvider',
          'imageGenUrl',
          'imageGenApiKey',
          'imageGenModel',
          'proximityRadiusTiles',
          'autoConverse',
          'narratorEnabled',
          'narratorName',
          'narratorStyle',
        ];
        for (const k of keys) {
          if (args[k] !== undefined) {
            (patch as any)[k] = args[k];
          }
        }
        this.hooks.updateSettings(patch);
        return {
          ok: true,
          settings: redactSettings({ ...DEFAULT_MODEL_SETTINGS, ...settings, ...patch }),
        };
      }

      case 'probe_api_models': {
        const provider = (args.provider ?? settings.localApiProvider ?? 'ollama') as ApiBrainProvider;
        const baseUrl = String(args.baseUrl ?? settings.localApiUrl ?? 'http://localhost:11434/v1');
        const apiKey = args.apiKey !== undefined ? String(args.apiKey) : settings.localApiKey;
        return probeApiModels(baseUrl, provider, apiKey);
      }

      case 'generate_image': {
        const res = await generateImageViaApi(
          {
            prompt: String(args.prompt || 'Fantasy pixel art scene'),
            kind: args.kind ?? 'scene',
            width: args.width ? Number(args.width) : 512,
            height: args.height ? Number(args.height) : 512,
            agentProvidedDataUrl: args.agentProvidedDataUrl,
          },
          settings,
        );
        if (args.applyToMapTileset) {
          const nextMap = { ...map, tileSetUrl: res.dataUrl };
          this.hooks.applyMap(nextMap);
        }
        if (args.applyToVillager) {
          const match = findVillagerMatch(villagers, String(args.applyToVillager));
          if (!match) throw new Error(`Villager "${args.applyToVillager}" not found.`);
          const updated = villagers.map((v) =>
            v.id === match.id
              ? {
                  ...v,
                  spritesheetId: 'custom',
                  appearance: undefined,
                  customSprite: {
                    textureUrl: res.dataUrl,
                    frameWidth: 32,
                    frameHeight: 32,
                    cols: 3,
                    rows: 4,
                    framesPerDirection: 3,
                    rowMap: { down: 0, left: 1, right: 2, up: 3 },
                  },
                }
              : v,
          );
          this.hooks.applyVillagers(updated);
        }
        return {
          ok: true,
          provider: res.provider,
          durationMs: res.durationMs,
          dataUrlPreview: `${res.dataUrl.slice(0, 64)}…`,
          dataUrl: res.dataUrl,
        };
      }

      case 'compose_pixel_pattern': {
        const name = String(args.name || 'Pixel Pattern').trim();
        const outCols = Math.max(1, Math.min(8, Math.round(Number(args.outCols ?? 1))));
        const outRows = Math.max(1, Math.min(8, Math.round(Number(args.outRows ?? 1))));
        const layer = (args.layer ?? 'bg1') as 'bg0' | 'bg1' | 'obj0' | 'obj1';
        const blocksMovement = Boolean(args.blocksMovement);
        const tileDim = Math.max(8, map.tileDim || 32);

        let gridWidth: number;
        let gridHeight: number;
        let palette: string[];
        let grid: number[];

        if (Array.isArray(args.asciiRows) && args.asciiRows.length > 0) {
          const parsed = parseAsciiPatternToGrid(args.asciiRows.map(String), args.paletteMap ?? {});
          gridWidth = parsed.gridWidth;
          gridHeight = parsed.gridHeight;
          palette = parsed.palette;
          grid = parsed.grid;
        } else {
          gridWidth = Math.max(1, Math.min(128, Math.round(Number(args.gridWidth ?? 16))));
          gridHeight = Math.max(1, Math.min(128, Math.round(Number(args.gridHeight ?? 16))));
          palette = Array.isArray(args.palette) ? args.palette.map(String) : [];
          grid = Array.isArray(args.grid)
            ? args.grid.map((n: any) => Math.round(Number(n)))
            : new Array<number>(gridWidth * gridHeight).fill(-1);
        }

        if (palette.length === 0) {
          throw new Error('compose_pixel_pattern requires non-empty palette + grid or asciiRows + paletteMap.');
        }

        const rendered = renderPixelGridToCanvases(
          grid,
          gridWidth,
          gridHeight,
          palette,
          outCols,
          outRows,
          tileDim,
        );
        const proceduralCode = generateProceduralCodeFromGrid(
          grid,
          gridWidth,
          gridHeight,
          palette,
          name,
        );

        let existingTilesetCanvas: HTMLCanvasElement | null = null;
        if (typeof document !== 'undefined' && typeof Image !== 'undefined' && map.tileSetUrl) {
          const loadedImg = await new Promise<HTMLImageElement | null>((resolve) => {
            const img = new Image();
            img.crossOrigin = 'anonymous';
            img.onload = () => resolve(img);
            img.onerror = () => resolve(null);
            img.src = resolvePublicUrl(map.tileSetUrl);
          });
          if (loadedImg) {
            const c = document.createElement('canvas');
            c.width = Math.max(tileDim, map.tileSetDimX || loadedImg.naturalWidth);
            c.height = Math.max(tileDim, map.tileSetDimY || loadedImg.naturalHeight);
            const ctx = c.getContext('2d');
            if (ctx) {
              ctx.imageSmoothingEnabled = false;
              ctx.drawImage(loadedImg, 0, 0);
              existingTilesetCanvas = c;
            }
          }
        }

        const curDimX = Math.max(tileDim * outCols, map.tileSetDimX || 256);
        const curDimY = Math.max(tileDim * outRows, map.tileSetDimY || 128);
        const autoSlot = existingTilesetCanvas
          ? findFirstEmptyTileBlock(existingTilesetCanvas, tileDim, outCols, outRows)
          : { col: 0, row: Math.floor(curDimY / tileDim) };

        const targetCol =
          typeof args.targetCol === 'number' ? Math.max(0, Math.round(args.targetCol)) : autoSlot.col;
        const targetRow =
          typeof args.targetRow === 'number' ? Math.max(0, Math.round(args.targetRow)) : autoSlot.row;

        const placed = await placeTilesInTilesetAt(
          existingTilesetCanvas,
          curDimX,
          curDimY,
          tileDim,
          rendered.canvases,
          targetCol,
          targetRow,
          outCols,
          outRows,
        );
        const stamp = createMacroStampFromIndices(
          name,
          outCols,
          outRows,
          placed.tileIndices,
          layer,
          blocksMovement,
        );

        let placedOnMap = false;
        let placedAt: { x: number; y: number } | null = null;
        if (args.applyToMap !== false) {
          const nextStamps = [
            ...(map.stamps ?? []).filter(
              (s) => !(s.tiles[0] === stamp.tiles[0] && s.width === stamp.width && s.height === stamp.height),
            ),
            stamp,
          ];
          let nextMap: VillageMap = {
            ...map,
            tileSetUrl: placed.newTilesetUrl,
            tileSetDimX: placed.newDimX,
            tileSetDimY: placed.newDimY,
            stamps: nextStamps,
          };
          if (args.placeAt && typeof args.placeAt.x === 'number' && typeof args.placeAt.y === 'number') {
            const px = Math.round(args.placeAt.x);
            const py = Math.round(args.placeAt.y);
            nextMap = applyMacroStampToMap(nextMap, stamp, px, py, layer, blocksMovement);
            placedOnMap = true;
            placedAt = { x: px, y: py };
          }
          this.hooks.applyMap(nextMap);
        }

        return {
          ok: true,
          name,
          stamp,
          startTileIndex: placed.startTileIndex,
          tileIndices: placed.tileIndices,
          tileSetDimX: placed.newDimX,
          tileSetDimY: placed.newDimY,
          placedOnMap,
          placedAt,
          previewDataUrl: rendered.previewDataUrl,
          proceduralCode,
        };
      }

      case 'export_bundle': {
        const scope = String(args.scope || 'project');
        const histories = sim.exportCharacterHistories();
        let json = '';
        if (scope === 'level') json = exportLevelJson(map);
        else if (scope === 'characters') json = exportCharactersJson(villagers);
        else if (scope === 'characters-history') json = exportCharactersWithHistoriesJson(villagers, histories);
        else if (scope === 'database') json = exportDatabaseJson(sim.conversations, histories, sim.focalWorldlineId);
        else {
          json = exportProjectJson({
            map,
            villagers,
            modelSettings: settings,
            conversations: sim.conversations,
            characterHistories: histories,
            focalWorldlineId: sim.focalWorldlineId,
            world: sim.world,
            savedAt: Date.now(),
          });
        }
        return { ok: true, scope, json };
      }

      case 'import_bundle': {
        const parsed = parseImportedVillageJson(String(args.json || ''));
        const importStore = this.hooks.getStore?.();
        if (importStore) {
          const commands: WorldCommand[] = [];
          if (parsed.world) commands.push({ type: 'context.update', patch: parsed.world });
          if (parsed.map) commands.push({ type: 'map.replace', map: parsed.map });
          if (parsed.villagers) commands.push({ type: 'cast.replace', cast: parsed.villagers });
          if (commands.length > 0) importStore.dispatchAll(commands, 'Import bundle');
        } else {
          if (parsed.world) sim.setWorld(parsed.world);
          if (parsed.map) this.hooks.applyMap(parsed.map);
          if (parsed.villagers) this.hooks.applyVillagers(parsed.villagers);
        }
        if (parsed.modelSettings) this.hooks.updateSettings(parsed.modelSettings);
        if (parsed.conversations) sim.replaceConversations(parsed.conversations);
        if (parsed.characterHistories) sim.applyCharacterHistories(parsed.characterHistories);
        if (parsed.focalWorldlineId) sim.setFocalWorldline(parsed.focalWorldlineId);
        this.hooks.persistAll?.();
        return { ok: true, format: parsed.format };
      }

      case 'apply_world_commands': {
        const store = this.requireStore();
        if (!Array.isArray(args.commands) || args.commands.length === 0) {
          throw new Error('commands must be a non-empty list.');
        }
        const doc = store.dispatchAll(args.commands as WorldCommand[], String(args.label || 'Agent edit'));
        return {
          ok: true,
          applied: args.commands.length,
          map: { name: doc.map.name, width: doc.map.width, height: doc.map.height },
          castSize: doc.cast.length,
          canUndo: store.canUndo,
        };
      }

      case 'undo_world_edit': {
        const store = this.requireStore();
        const undone = store.undo();
        return { ok: undone !== null, undone, canUndo: store.canUndo, canRedo: store.canRedo };
      }

      case 'redo_world_edit': {
        const store = this.requireStore();
        const redone = store.redo();
        return { ok: redone !== null, redone, canUndo: store.canUndo, canRedo: store.canRedo };
      }

      case 'clear_database': {
        brainRouter.flushAudioQueue();
        sim.clearDatabase();
        this.hooks.persistAll?.();
        return { ok: true };
      }

      default:
        throw new Error(`Unknown SeloAI tool "${name}".`);
    }
  }
}

